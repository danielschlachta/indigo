/**
 * Type information for idg_filter.
 */
class idg_filter_type extends idg_treenode_type {

    function __construct() {
        parent::__construct(false);

        $this->child_types = [];
        $this->set_property_mandatory('name');

        $this->register_property('load');
        $this->register_property('apply');
    }
}

/**
 * A filter filters.
 * <p>If either the <code>load</code> property is specified or the object
 * has character data, it is considered a declaration. 
 * The text is then considered a function with the following signature:
 * 
 *      function (idg_view $view, string $text): ?string
 * 
 * The text generated by the parent element and its siblings is passed as 
 * <code>$text</code> and replaced with the return value. 
 * If the filter returns <code>null</code> it is ignored. If multiple filters are
 * present, they are processed in order.<p>
 * <p>The declared filter is not applied by default, this can be changed by setting the
 * property <code>apply</code> to <code>yes</code>.</p>
 * <p>If no text is specified, a filter function by the same name that must have been 
 * declared earlier (i.e. it can be a global function) is invoked on the parent element 
 * instead, unless <code>apply</code> is set to <code>no</code> in which case it remains 
 * inactive but error checking is still performed (useful for debugging).</p>
 */
class idg_filter extends idg_treenode {

    function __construct() {
        parent::__construct('filter');
    }

    /**
     * Loads a file and calls set_text() with the result.
     * If text is already present, it is overwritten.
     * <blockquote>
     * Note: The text may be prefixed with <code>&lt;?php</code>
     * which is simply stripped. This is convenient for use with 
     * editors which are aware of <code>php</code> syntax.
     * </blockquote>
     * @param string $filename
     * @return void
     */
    function load(string $filename): void {
        $filter = @file_get_contents($filename);

        if (!$filter)
            idg_diag($this, "filter '$filename' could not be loaded");

        $this->set_text(preg_replace('/^\<\?php[ \t\n]*/', '', $filter));
    }

    /**
     * Gets executed in various places to do the actual work.
     * @param idg_view $view The view with which to register
     */
    function apply_filter(idg_view $view): void {
        if (($load = $this->get_property('load')))
            $this->load($load);

        $name = $this->get_property('name');
        $apply = $this->get_property('apply');

        if ($text = $this->get_text()) {
            eval("function $name(idg_view \$view, string \$text): ?string { $text }"); 
            if ($apply == "yes")
                $view->add_filter($name);
            
        } else if ($apply != "no")
            $view->add_filter($name);
    }
}
